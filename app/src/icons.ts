export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

/** The lit cells of a bitmap as one SVG path: a rectangle per run of "#" in a row. */
export function bitmapPath(rows: readonly string[]): string {
  let d = "";
  rows.forEach((row, y) => {
    for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  return d;
}

export function iconRows(name: IconName): readonly string[] {
  return ICONS[name];
}

/** Inline SVG markup for an icon, `size` CSS pixels square. Hidden from screen readers: the button's aria-label names it. */
export function iconSvg(name: IconName, size = 18): string {
  return `<svg class="icon" viewBox="0 0 12 12" width="${size}" height="${size}" aria-hidden="true" focusable="false" shape-rendering="crispEdges"><path fill="currentColor" d="${bitmapPath(ICONS[name])}"/></svg>`;
}
